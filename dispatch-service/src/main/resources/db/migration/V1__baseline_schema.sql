-- Схема, яку раніше створював Hibernate (ddl-auto=update). Наявні бази пропускають цю міграцію
-- (spring.flyway.baseline-on-migrate, baseline-version=1).

CREATE TABLE couriers (
    user_id              bigint                      NOT NULL PRIMARY KEY,
    display_name         varchar(100),
    phone                varchar(32),
    work_zone            varchar(255)                NOT NULL,
    work_zone_code       varchar(19),
    max_package_weight   numeric(38, 2)              NOT NULL,
    is_available         boolean                     NOT NULL,
    last_known_latitude  double precision,
    last_known_longitude double precision,
    location_updated_at  timestamp(6) with time zone,
    last_assigned_at     timestamp(6) with time zone
);

CREATE TABLE dispatch_requests (
    shipment_id        bigint                      NOT NULL PRIMARY KEY,
    sender_id          bigint,
    pickup_address     varchar(255),
    pickup_city_code   varchar(19),
    pickup_latitude    double precision,
    pickup_longitude   double precision,
    delivery_address   varchar(255),
    delivery_city_code varchar(19),
    delivery_latitude  double precision,
    delivery_longitude double precision,
    parcel_weight      numeric(38, 2),
    distance_km        numeric(38, 2),
    price              numeric(38, 2),
    delivery_type      varchar(20),
    status             varchar(255)                NOT NULL,
    search_attempts    integer                     NOT NULL,
    last_search_at     timestamp(6) with time zone,
    delay_notified_at  timestamp(6) with time zone,
    created_at         timestamp(6) with time zone NOT NULL,
    updated_at         timestamp(6) with time zone NOT NULL,
    CONSTRAINT dispatch_requests_status_check CHECK (status IN
        ('SEARCHING', 'OFFERED', 'WAITING_FOR_COURIERS', 'ASSIGNED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE delivery_offers (
    offer_id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id           bigint                         NOT NULL,
    user_id               bigint                         NOT NULL REFERENCES couriers (user_id),
    status                varchar(255)                   NOT NULL,
    created_at            timestamp(6) with time zone,
    expires_at            timestamp(6) without time zone NOT NULL,
    responded_at          timestamp(6) with time zone,
    distance_to_pickup_km double precision,
    CONSTRAINT delivery_offers_status_check CHECK (status IN
        ('PENDING', 'ACCEPTED', 'REJECTED', 'EXPIRED', 'CANCELLED'))
);

CREATE INDEX idx_offer_status_expires ON delivery_offers (status, expires_at);
CREATE INDEX idx_offer_shipment ON delivery_offers (shipment_id);

CREATE TABLE assignments (
    assignment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id   bigint                         NOT NULL,
    user_id       bigint                         NOT NULL REFERENCES couriers (user_id),
    status        varchar(255)                   NOT NULL,
    assigned_at   timestamp(6) with time zone,
    picked_up_at  timestamp(6) with time zone,
    ended_at      timestamp(6) without time zone,
    end_reason    varchar(500),
    CONSTRAINT assignments_status_check CHECK (status IN
        ('ACTIVE', 'COMPLETED', 'COURIER_WITHDREW', 'CANCELLED'))
);

CREATE INDEX idx_assignment_shipment ON assignments (shipment_id);

CREATE TABLE outbox_events (
    event_id     uuid                        NOT NULL PRIMARY KEY,
    aggregate_id varchar(255)                NOT NULL,
    event_type   varchar(255)                NOT NULL,
    payload      text                        NOT NULL,
    traceparent  varchar(255),
    published    boolean                     NOT NULL,
    created_at   timestamp(6) with time zone NOT NULL,
    published_at timestamp(6) with time zone
);

CREATE INDEX idx_outbox_unpublished ON outbox_events (published, created_at);

CREATE TABLE processed_events (
    event_id     uuid                        NOT NULL PRIMARY KEY,
    event_type   varchar(255)                NOT NULL,
    processed_at timestamp(6) with time zone NOT NULL
);
