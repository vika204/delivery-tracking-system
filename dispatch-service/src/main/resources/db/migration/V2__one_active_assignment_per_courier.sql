-- Кур'єр виконує не більше однієї доставки одночасно. Основний захист — блокування рядка кур'єра
-- в AcceptCourierProposal; індекс страхує від гонок, які обійшли б його.
-- Увага: на наявній базі міграція впаде, якщо в кур'єра вже кілька ACTIVE-призначень
-- (раніше дозволялося до трьох) — їх треба завершити до розгортання.
CREATE UNIQUE INDEX uq_assignment_active_courier ON assignments (user_id) WHERE status = 'ACTIVE';
