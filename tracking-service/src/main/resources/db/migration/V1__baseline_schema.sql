-- Схема, яку раніше створював Hibernate (ddl-auto=update). Наявні бази пропускають цю міграцію
-- (spring.flyway.baseline-on-migrate, baseline-version=1).

CREATE TABLE locations (
    location_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id bigint                         NOT NULL,
    latitude    numeric(9, 6)                  NOT NULL,
    longitude   numeric(9, 6)                  NOT NULL,
    recorded_at timestamp(6) without time zone NOT NULL
);

CREATE TABLE route_uploads (
    upload_id         varchar(64)                 NOT NULL PRIMARY KEY,
    shipment_id       bigint                      NOT NULL,
    received_count    integer                     NOT NULL,
    saved_count       integer                     NOT NULL,
    rejected_count    integer                     NOT NULL,
    first_location_id bigint,
    last_location_id  bigint,
    created_at        timestamp(6) with time zone NOT NULL
);
