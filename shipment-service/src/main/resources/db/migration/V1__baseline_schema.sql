-- Схема, яку раніше створював Hibernate (ddl-auto=update). Наявні бази пропускають цю міграцію
-- (spring.flyway.baseline-on-migrate, baseline-version=1).

CREATE TABLE shipments (
    shipment_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               bigint                         NOT NULL,
    sender_name           varchar(255),
    sender_phone          varchar(255),
    recipient_name        varchar(255)                   NOT NULL,
    recipient_phone       varchar(255)                   NOT NULL,
    pickup_address        varchar(255)                   NOT NULL,
    pickup_city_code      varchar(19),
    pickup_latitude       double precision,
    pickup_longitude      double precision,
    delivery_address      varchar(255)                   NOT NULL,
    delivery_city_code    varchar(19),
    delivery_latitude     double precision,
    delivery_longitude    double precision,
    weight                numeric(38, 2)                 NOT NULL,
    length                numeric(38, 2)                 NOT NULL,
    width                 numeric(38, 2)                 NOT NULL,
    height                numeric(38, 2)                 NOT NULL,
    distance              numeric(38, 2)                 NOT NULL,
    price                 numeric(38, 2)                 NOT NULL,
    delivery_type         varchar(255),
    quote_id              uuid,
    status                varchar(255)                   NOT NULL,
    assigned_courier_id   bigint,
    assigned_courier_name varchar(100),
    assigned_at           timestamp(6) with time zone,
    trip_started_at       timestamp(6) with time zone,
    picked_up_at          timestamp(6) with time zone,
    delivered_at          timestamp(6) with time zone,
    cancelled_at          timestamp(6) with time zone,
    cancellation_reason   varchar(500),
    created_at            timestamp(6) without time zone NOT NULL,
    updated_at            timestamp(6) without time zone NOT NULL DEFAULT now(),
    version               bigint                         NOT NULL DEFAULT 0,
    CONSTRAINT shipments_delivery_type_check CHECK (delivery_type IN ('STANDARD', 'EXPRESS')),
    CONSTRAINT shipments_status_check CHECK (status IN
        ('WAITING_FOR_COURIER', 'ASSIGNED', 'TO_PICKUP', 'IN_TRANSIT', 'DELIVERED', 'CANCELLED'))
);

CREATE TABLE shipment_status_history (
    history_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id bigint                      NOT NULL,
    from_status varchar(255),
    to_status   varchar(255)                NOT NULL,
    changed_at  timestamp(6) with time zone NOT NULL,
    actor_type  varchar(255)                NOT NULL,
    actor_id    bigint,
    reason      varchar(500),
    CONSTRAINT shipment_status_history_actor_type_check CHECK (actor_type IN ('SENDER', 'COURIER', 'SYSTEM')),
    CONSTRAINT shipment_status_history_from_status_check CHECK (from_status IN
        ('WAITING_FOR_COURIER', 'ASSIGNED', 'TO_PICKUP', 'IN_TRANSIT', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT shipment_status_history_to_status_check CHECK (to_status IN
        ('WAITING_FOR_COURIER', 'ASSIGNED', 'TO_PICKUP', 'IN_TRANSIT', 'DELIVERED', 'CANCELLED'))
);

CREATE INDEX idx_status_history_shipment ON shipment_status_history (shipment_id);

CREATE TABLE price_quotes (
    quote_id                 uuid                        NOT NULL PRIMARY KEY,
    user_id                  bigint                      NOT NULL,
    pickup_address           varchar(255)                NOT NULL,
    pickup_city_code         varchar(19)                 NOT NULL,
    pickup_latitude          double precision            NOT NULL,
    pickup_longitude         double precision            NOT NULL,
    delivery_address         varchar(255)                NOT NULL,
    delivery_city_code       varchar(19)                 NOT NULL,
    delivery_latitude        double precision            NOT NULL,
    delivery_longitude       double precision            NOT NULL,
    distance_km              numeric(38, 2)              NOT NULL,
    weight                   numeric(38, 2)              NOT NULL,
    delivery_type            varchar(255)                NOT NULL,
    base_price               numeric(38, 2)              NOT NULL,
    price_per_km             numeric(38, 2)              NOT NULL,
    price_per_kg             numeric(38, 2)              NOT NULL,
    distance_charge          numeric(38, 2)              NOT NULL,
    weight_charge            numeric(38, 2)              NOT NULL,
    delivery_type_multiplier numeric(38, 2)              NOT NULL,
    total_price              numeric(38, 2)              NOT NULL,
    calculated_at            timestamp(6) with time zone NOT NULL,
    expires_at               timestamp(6) with time zone NOT NULL,
    shipment_id              bigint,
    CONSTRAINT price_quotes_delivery_type_check CHECK (delivery_type IN ('STANDARD', 'EXPRESS'))
);

CREATE TABLE idempotency_records (
    record_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key varchar(255)                   NOT NULL UNIQUE,
    request_hash    varchar(64)                    NOT NULL,
    shipment_id     bigint                         NOT NULL,
    created_at      timestamp(6) without time zone NOT NULL
);

CREATE TABLE outbox_events (
    event_id       uuid                           NOT NULL PRIMARY KEY,
    aggregate_type varchar(255)                   NOT NULL,
    aggregate_id   varchar(255)                   NOT NULL,
    event_type     varchar(255)                   NOT NULL,
    payload        text                           NOT NULL,
    traceparent    varchar(255),
    published      boolean                        NOT NULL,
    created_at     timestamp(6) without time zone NOT NULL,
    published_at   timestamp(6) without time zone
);

CREATE TABLE processed_events (
    event_id     uuid                        NOT NULL PRIMARY KEY,
    event_type   varchar(255)                NOT NULL,
    processed_at timestamp(6) with time zone NOT NULL
);
